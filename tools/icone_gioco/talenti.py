from motore import Cv, process, overlay

T = {}

def volante():
    c = Cv(16)
    c.ring(7.5, 7.5, 7.0, 5.1, 'D')
    c.rect(2, 7, 13, 8, 'D'); c.rect(7, 9, 8, 13, 'D')
    c.disc(7.5, 7.5, 2.3, 'S')
    r = process(c.rows())
    fix = ['................']*6 + ['.......RR.......', '......RRRR......'.replace('RRRR','eRRr'), '.......rr.......'] + ['................']*7
    fix = ['................']*6 + ['......KRRK......', '......KeRK......', '......KrrK......'][:0] + ['................']*10
    fix[7] = '.......RR.......'; fix[8] = '.......RR.......'
    return overlay(r, fix)
T['Un milione di km al volante'] = ('mix', volante)

def allergico():
    c = Cv(16)
    c.rect(1, 2, 14, 11, 'S'); c.rect(3, 4, 12, 9, 'B')
    c.rect(6, 12, 9, 12, 'S'); c.rect(4, 13, 11, 13, 'S')
    r = process(c.rows())
    # X rossa sullo schermo
    fix = ['.'*16 for _ in range(16)]
    fix = [list(x) for x in fix]
    for i in range(6):
        fix[4+i][4+i+1] = 'R'; fix[4+i][11-i-1] = 'R'
    for i in range(6):
        fix[4+i][4+i] = 'r' if fix[4+i][4+i] == '.' else fix[4+i][4+i]
    return overlay(r, [''.join(f) for f in fix])
T['Allergico al gestionale'] = ('neg', allergico)

